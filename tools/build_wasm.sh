#!/bin/sh
# Builds the shared engine (engine/dfd_acid.h) to WebAssembly and writes web/dfd-wasm.js (base64, so the page also works offline).
set -e
cd "$(dirname "$0")/.."
mkdir -p build
${CLANG:-clang++} --target=wasm32 -std=c++17 -O3 -ffast-math -nostdlib -fno-exceptions -fno-rtti -fno-threadsafe-statics \
  -fvisibility=hidden -mbulk-memory -Wl,--no-entry -Wl,--export-dynamic -Wl,--export=__wasm_call_ctors \
  -Wl,--initial-memory=33554432 -Wl,--max-memory=33554432 -Wl,--allow-undefined -Iengine engine/wasm.cpp -o build/dfd.wasm
python3 - <<'P'
import base64
b=open('build/dfd.wasm','rb').read()
open('web/dfd-wasm.js','w').write('// generated by tools/build_wasm.sh from engine/dfd_acid.h, do not edit\nexport const WASM_B64="'+base64.b64encode(b).decode()+'";\n')
print('web/dfd-wasm.js', len(b), 'bytes of wasm')
P
